package io.github.muntasimulhaque.crayoner.ui

import androidx.compose.ui.unit.dp

/**
 * The app's one coin: the round press a child hits with a thumb. Every round
 * control in the app is this size, in the bar and on the capsule alike, so
 * the marks inside them can be drawn at one size too and the whole screen
 * reads as one hand's work. It is comfortably past the 48 dp a fingertip
 * needs, and it is the number the bar and the capsule both measure from.
 */
internal val CoinSize = 52.dp

/**
 * The size of a mark inside a coin. The house and the speaker in the bar, the
 * crayon, the two steps and the rubber on the capsule: one size, so no row of
 * buttons reads as a row of different apps.
 */
internal val IconSize = 26.dp
